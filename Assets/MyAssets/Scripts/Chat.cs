    #region RemovePrefix

// It is used to remove the name prefix in AI generated sentences, such as "XXX:", so if there is a colon in the first ten characters, remove the colon and the characters before it, and all Chinese characters need to be removed
    public string RemovePrefixChinese(string result)
    {
        string newString;

        if (result.Length >= 10)
        {
            string firstTenChars = result.Substring(0, 10);
            int indexOfColon = firstTenChars.IndexOf("：", StringComparison.Ordinal);
            if (indexOfColon != -1)
            {
                newString = result.Substring(indexOfColon + 1);
            }
            else
            {
                newString = result;
            }
        }
        else
        {
            newString = result;
        }

        Debug.Log("New string: " + newString);
        return newString;
    }

