    // Core sending code
    public async Task GetChatCompletion(string userContent, string systemContent = "",
        string aiSettingPrompt = "")
    {
        ControlHistoryCount();

        // Send the history as a string
        string conversationHistoryString = string.Join("\n", conversationHistory);

        // The "\n" is added to prevent the sentences from being mixed together, making it easier for the AI ​​to understand. If it is not added, there is a chance that the AI ​​will ignore some words. You can try it yourself.
        aiSettingPrompt = "\n" + requirementSetting + "\n" + characterSetting + "\n" + toneSetting;
        userContent = this.userContent;
        systemContent = this.aiContent;

        // API Key
        var api = new OpenAIClient(openaiKey);


#if UNITY_EDITOR
        // Check if the ChatEndpoint property is empty. ChatEndpoint is the API endpoint of OpenAI's Chat function.
        //Assert.IsNotNull(api.ChatEndpoint);
#endif

        // Define ChatPrompt, including roles and content. Role is the name of the defined AI, and content can be predefined AI
        var messages = new List<Message>
        {
            // Passing the conversation history to Role.System allows the AI ​​to answer based on the context.
            new Message(Role.System, systemContent + aiSettingPrompt + conversationHistoryString),

            // The brackets are used to control the AI ​​to generate answers. You can also change them to other symbols without the AI ​​answering.
            new Message(Role.User, userContent),
        };


        // If the parameter stop is serialized, it must be assigned a value, otherwise the generation will stop.
        var chatRequest =  new ChatRequest(
messages: messages,
model: model,
temperature: temperature,
topP: topP,
number: number,
stops: stop,
maxTokens: maxTokens,
presencePenalty: presencePenalty,
frequencyPenalty: frequencyPenalty,
logitBias: logitBias,
user: userId);

        // Call the API to get the AI ​​text
        var result = await api.ChatEndpoint.GetCompletionAsync(chatRequest);
        // Fixed the issue where AI would return the name prefix when talking to the user, so remove the Chinese and English colons
        var removeEnglishColon = RemovePrefixEnglish(result.FirstChoice);
        var finalResult = RemovePrefixChinese(removeEnglishColon);

#if UNITY_EDITOR
        // Check if the result is empty
        Assert.IsNotNull(result);
        // Check if the AI ​​generated article is empty
        Assert.NotNull(result.Choices);
        // Check if the number of AI generated articles is 0
        Assert.NotZero(result.Choices.Count);
#endif

        // The ChatGpt API will return multiple texts. We select the first one.  
        Debug.Log(result.FirstChoice);

        // Add reply record
        GameObject newGameObject = Instantiate(dialogueHistory);
        newGameObject.transform.SetParent(scrollContent);
        newGameObject.SetActive(true);
        TMP_Text text = newGameObject.transform.GetChild(0).GetComponent<TMP_Text>();
        text.text = "<color=#91B493>AI</color>" + "\n" + finalResult;


        // Add the TypewriterEffect component to the TMP_Text that needs to achieve the typewriter effect, and then call the ShowText method.
        // Realize the text typewriter effect
        TypewriterEffect typewriterEffect = aiResponseText.GetComponent<TypewriterEffect>();
        StartCoroutine(typewriterEffect.ShowText(finalResult, aiResponseText));

        // Perform text-to-language conversion
        TextToSpeech tts = this.GetComponent<TextToSpeech>();
        tts.AzureTextToSpeech(finalResult);

        // Recording conversations
        conversationHistory.Add("System:" + finalResult + "\n");

        // After returning the text, close the waiting UI
        loadingUI.SetActive(false);
    }

    // Bound to the send button to send player input information
    public void SendToAIMessage()
    {
        if (playerInputField.text == string.Empty)
        {
            return;
        }


        // Content sent by players
        userContent = playerInputField.text;

        // Recording conversations
        conversationHistory.Add("User:" + userContent + "\n");

        // Calling the API
        GetChatCompletion(userContent);

        // Clear the input box
        playerInputField.text = "";

        DialogueRecord();
        loadingUI.SetActive(true);
    }

